"""Native PipeWire engine pieces: config rendering, pw-dump lookups, live control changes.

The engine is a second ``pipewire`` process started with our own config. It connects to the
user's running PipeWire daemon as a client and hosts three things:

* one ``filter-chain`` per speaker whose only node is a sample-accurate ``delay`` (the
  manual sync offset, adjustable live with ``pw-cli set-param``),
* one ``combine-stream`` sink that every app plays into, with resampler-based drift
  correction per output and optional automatic latency compensation.

No EQ, no dynamics, no format change beyond PipeWire's float32 mixing.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Sequence

from .errors import AudioError
from .runner import Runner

DELAY_NODE = "delay"  # name of the filter node inside each filter-chain graph
DELAY_CONTROL = f"{DELAY_NODE}:Delay (s)"
MAX_DELAY_S = 1.0


def spa_string(value: str) -> str:
    return json.dumps(value)  # SPA JSON accepts JSON string literals


@dataclass
class OutputPlan:
    position: str
    label: str
    sink_node: str  # node.name of the Bluetooth sink in PipeWire
    offset_ms: float = 0.0

    @property
    def delay_node_name(self) -> str:
        return f"soundscape_{self.position}_delay"

    @property
    def channel_positions(self) -> Optional[Sequence[str]]:
        """Which combine channels this output takes when stereo-split is on."""
        return {"left": ("FL", "FL"), "right": ("FR", "FR")}.get(self.position)


@dataclass
class EnginePlan:
    outputs: List[OutputPlan]
    sink_name: str = "soundscape"
    description: str = "Soundscape (both speakers)"
    latency_compensate: bool = True
    resample_quality: int = 10
    stereo_split: bool = False
    with_delays: bool = True

    def target_for(self, out: OutputPlan) -> str:
        return out.delay_node_name if self.with_delays else out.sink_node


def _delay_filter(out: OutputPlan) -> str:
    desc = spa_string(f"Soundscape internal: {out.label} delay (do not select)")
    return f"""    {{ name = libpipewire-module-filter-chain
      args = {{
        node.description = {desc}
        media.name = {desc}
        filter.graph = {{
          nodes = [
            {{ type = builtin label = delay name = {DELAY_NODE}
              config = {{ "max-delay" = {MAX_DELAY_S:.1f} }}
              control = {{ "Delay (s)" = {out.offset_ms / 1000.0:.6f} }} }}
          ]
        }}
        audio.channels = 2
        audio.position = [ FL FR ]
        capture.props = {{
          node.name = {spa_string(out.delay_node_name)}
          media.class = Audio/Sink
          node.description = {desc}
          audio.position = [ FL FR ]
        }}
        playback.props = {{
          node.name = {spa_string(out.delay_node_name + ".output")}
          node.passive = true
          node.dont-reconnect = true
          stream.dont-remix = true
          target.object = {spa_string(out.sink_node)}
        }}
      }}
    }}
"""


def _stream_rule(plan: EnginePlan, out: OutputPlan) -> str:
    props = ""
    if plan.stereo_split and out.channel_positions:
        props = (f"combine.audio.position = [ {' '.join(out.channel_positions)} ] "
                 f"audio.position = [ FL FR ]")
    return (f"          {{ matches = [ {{ node.name = {spa_string(plan.target_for(out))} }} ]\n"
            f"            actions = {{ create-stream = {{ {props} }} }} }}\n")


def render_config(plan: EnginePlan) -> str:
    if not plan.outputs:
        raise AudioError("engine plan has no outputs")
    parts = [
        "# Generated by Soundscape. Edits are overwritten by `soundscape up`.\n",
        "context.properties = {\n    log.level = 2\n}\n",
        "context.spa-libs = {\n    audio.convert.* = audioconvert/libspa-audioconvert\n"
        "    support.*       = support/libspa-support\n}\n",
        "context.modules = [\n",
        "    { name = libpipewire-module-rt args = { nice.level = -11 } flags = [ ifexists nofail ] }\n",
        "    { name = libpipewire-module-protocol-native }\n",
        "    { name = libpipewire-module-client-node }\n",
        "    { name = libpipewire-module-adapter }\n",
    ]
    if plan.with_delays:
        parts.extend(_delay_filter(out) for out in plan.outputs)
    parts.append(
        f"    {{ name = libpipewire-module-combine-stream\n"
        f"      args = {{\n"
        f"        combine.mode = sink\n"
        f"        node.name = {spa_string(plan.sink_name)}\n"
        f"        node.description = {spa_string(plan.description)}\n"
        f"        combine.latency-compensate = {'true' if plan.latency_compensate else 'false'}\n"
        f"        combine.props = {{ audio.position = [ FL FR ] }}\n"
        f"        stream.props = {{ resample.quality = {int(plan.resample_quality)} }}\n"
        f"        stream.rules = [\n"
    )
    parts.extend(_stream_rule(plan, out) for out in plan.outputs)
    parts.append("        ]\n      }\n    }\n]\n")
    return "".join(parts)


# -- runtime -------------------------------------------------------------------

def parse_version(text: str) -> Optional[str]:
    m = re.search(r"libpipewire\s+(\d+\.\d+\.\d+)", text) or re.search(r"(\d+\.\d+\.\d+)", text)
    return m.group(1) if m else None


def version_tuple(version: Optional[str]) -> tuple:
    if not version:
        return (0, 0, 0)
    return tuple(int(p) for p in version.split(".")[:3])


class PipeWireCtl:
    def __init__(self, runner: Runner):
        self.runner = runner

    def version(self) -> Optional[str]:
        if not self.runner.which("pipewire"):
            return None
        res = self.runner.run(["pipewire", "--version"], timeout=10)
        return parse_version(res.stdout + res.stderr) if res.ok or res.stdout else None

    def dump(self) -> List[Dict[str, Any]]:
        self.runner.require("pw-dump")
        res = self.runner.run(["pw-dump"], timeout=15)
        if not res.ok:
            raise AudioError(f"pw-dump failed: {res.stderr.strip()}")
        try:
            data = json.loads(res.stdout)
        except json.JSONDecodeError as exc:
            raise AudioError(f"pw-dump returned malformed JSON: {exc}") from exc
        return data if isinstance(data, list) else []

    def node_id(self, node_name: str) -> Optional[int]:
        for obj in self.dump():
            if obj.get("type") != "PipeWire:Interface:Node":
                continue
            props = (obj.get("info") or {}).get("props") or {}
            if props.get("node.name") == node_name:
                return int(obj["id"])
        return None

    def node_names(self) -> List[str]:
        names = []
        for obj in self.dump():
            if obj.get("type") == "PipeWire:Interface:Node":
                name = ((obj.get("info") or {}).get("props") or {}).get("node.name")
                if name:
                    names.append(str(name))
        return names

    def set_delay(self, node_name: str, seconds: float) -> None:
        if not 0 <= seconds <= MAX_DELAY_S:
            raise AudioError(f"delay {seconds * 1000:.1f} ms is outside 0..{MAX_DELAY_S * 1000:.0f} ms")
        node = self.node_id(node_name)
        if node is None:
            raise AudioError(f"delay node {node_name} is not in the graph",
                             "is the Soundscape engine running? try `soundscape up`")
        self.runner.require("pw-cli")
        param = f'{{ params = [ "{DELAY_CONTROL}" {seconds:.6f} ] }}'
        res = self.runner.run(["pw-cli", "set-param", str(node), "Props", param], timeout=10)
        if not res.ok:
            raise AudioError(f"pw-cli set-param failed: {(res.stderr or res.stdout).strip()}")
